package io.github.classgraph;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.lang.annotation.Annotation;
import java.lang.annotation.Inherited;
import java.lang.annotation.Repeatable;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.nio.file.Files;
import java.nio.file.Path;

import javax.tools.ToolProvider;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * A repeatable annotation applied more than once is stored in the classfile as a single container annotation
 * holding the repeats, rather than as several annotations. ClassGraph reports both, the way the JDK does: the
 * container stays in the annotation list, as in {@link Class#getAnnotations()}, and the repeats are listed beside
 * it in the order they were written, as in {@link Class#getAnnotationsByType(Class)}.
 */
public class RepeatableAnnotationTest {
    /** The container that holds the repeats of {@link Tag}. */
    @Retention(RetentionPolicy.RUNTIME)
    public @interface Tags {
        /**
         * The repeats.
         *
         * @return the repeats.
         */
        Tag[] value();
    }

    /** A repeatable annotation. */
    @Repeatable(Tags.class)
    @Retention(RetentionPolicy.RUNTIME)
    public @interface Tag {
        /**
         * The name of the tag.
         *
         * @return the name of the tag.
         */
        String value();
    }

    /** An annotation that is not repeatable. */
    @Retention(RetentionPolicy.RUNTIME)
    public @interface NotRepeatable {
    }

    /**
     * A class carrying two repeats of the repeatable annotation, so the classfile holds the container. The repeats
     * are written out of alphabetical order, so that sorting them by value would change their order.
     */
    @Tag("second")
    @Tag("first")
    @NotRepeatable
    public static class TaggedTwice {
        /** A method carrying two repeats of the repeatable annotation. */
        @Tag("twice")
        @Tag("on a method")
        public void method() {
        }
    }

    /** A class carrying the container annotation written out explicitly, rather than generated by the compiler. */
    @Tags({ @Tag("y"), @Tag("x") })
    public static class ExplicitContainer {
    }

    /** A class carrying one use of the repeatable annotation, so the classfile holds no container. */
    @Tag("only")
    public static class TaggedOnce {
    }

    /** A class carrying no repeatable annotation at all. */
    public static class NotTagged {
    }

    /** An annotation that subclasses inherit. */
    @Inherited
    @Retention(RetentionPolicy.RUNTIME)
    public @interface InheritedTag {
    }

    /** A class carrying the inherited annotation. */
    @InheritedTag
    public static class InheritedTagBase {
    }

    /** A class that inherits the annotation, rather than carrying it. */
    public static class InheritsTag extends InheritedTagBase {
    }

    /** The container that holds the repeats of {@link InheritedRepeat}. */
    @Inherited
    @Retention(RetentionPolicy.RUNTIME)
    public @interface InheritedRepeats {
        /**
         * The repeats.
         *
         * @return the repeats.
         */
        InheritedRepeat[] value();
    }

    /** A repeatable annotation that subclasses inherit. */
    @Inherited
    @Repeatable(InheritedRepeats.class)
    @Retention(RetentionPolicy.RUNTIME)
    public @interface InheritedRepeat {
        /**
         * The name of the repeat.
         *
         * @return the name of the repeat.
         */
        String value();
    }

    /** A class carrying two repeats of the inherited repeatable annotation. */
    @InheritedRepeat("second")
    @InheritedRepeat("first")
    public static class InheritedRepeatBase {
    }

    /** A class that inherits both repeats, rather than carrying them. */
    public static class InheritsRepeats extends InheritedRepeatBase {
    }

    /** The name of the repeatable annotation in the compiled module. */
    private static final String MODULE_TAG = "com.xyz.rep.R";

    /** The name of the container of {@link #MODULE_TAG} in the compiled module. */
    private static final String MODULE_TAGS = "com.xyz.rep.Rs";

    /** The scan of the test classes. */
    private static ScanResult scanResult;

    /** The directory holding the compiled module. */
    private static Path moduleDir;

    /** A second directory, holding only a copy of the compiled module's {@code package-info.class}. */
    private static Path packageInfoCopyDir;

    /** A third directory, holding only a copy of the compiled module's {@code module-info.class}. */
    private static Path moduleInfoCopyDir;

    /** Scan the test classes. */
    @BeforeAll
    static void scan() {
        scanResult = new ClassGraph().enableClasspath()
                .acceptClasses(RepeatableAnnotationTest.class.getName() + "$*").enableClassInfo().enableFieldInfo()
                .enableMethodInfo().enableAnnotationInfo().enableStaticFinalFieldConstantInitializerValues()
                .ignoreClassVisibility().ignoreFieldVisibility().ignoreMethodVisibility().scan();
    }

    /**
     * Compile a module whose module declaration and package both carry repeats of a repeatable annotation, copy the
     * package's {@code package-info.class} into a second directory, and copy the {@code module-info.class} into a
     * third.
     *
     * @param tempDir
     *            the temporary directory to compile in.
     * @throws IOException
     *             if the sources could not be written, or the classfile could not be copied.
     */
    @BeforeAll
    static void compileModule(@TempDir final Path tempDir) throws IOException {
        final var srcDir = tempDir.resolve("src");
        final var packageDir = srcDir.resolve("com/xyz/rep");
        Files.createDirectories(packageDir);
        final var moduleInfoSrc = srcDir.resolve("module-info.java");
        Files.writeString(moduleInfoSrc, """
                @com.xyz.rep.R("b")
                @com.xyz.rep.R("a")
                @com.xyz.rep.R("a")
                module com.xyz.rep {
                    exports com.xyz.rep;
                }
                """);
        final var packageInfoSrc = packageDir.resolve("package-info.java");
        Files.writeString(packageInfoSrc, """
                @R("b")
                @R("a")
                @R("a")
                package com.xyz.rep;
                """);
        final var tagSrc = packageDir.resolve("R.java");
        Files.writeString(tagSrc, """
                package com.xyz.rep;

                import java.lang.annotation.Repeatable;
                import java.lang.annotation.Retention;
                import java.lang.annotation.RetentionPolicy;

                @Repeatable(Rs.class)
                @Retention(RetentionPolicy.RUNTIME)
                public @interface R {
                    String value();
                }
                """);
        final var tagsSrc = packageDir.resolve("Rs.java");
        Files.writeString(tagsSrc, """
                package com.xyz.rep;

                import java.lang.annotation.Retention;
                import java.lang.annotation.RetentionPolicy;

                @Retention(RetentionPolicy.RUNTIME)
                public @interface Rs {
                    R[] value();
                }
                """);

        moduleDir = tempDir.resolve("classes");
        Files.createDirectories(moduleDir);
        final var compiler = ToolProvider.getSystemJavaCompiler();
        assertThat(compiler).as("the tests must be run on a JDK, not a JRE").isNotNull();
        final var exitCode = compiler.run(/* in = */ null, /* out = */ null, /* err = */ null, "-d",
                moduleDir.toString(), moduleInfoSrc.toString(), packageInfoSrc.toString(), tagSrc.toString(),
                tagsSrc.toString());
        assertThat(exitCode).as("javac exit code").isZero();

        packageInfoCopyDir = tempDir.resolve("copy");
        final var copiedPackageDir = packageInfoCopyDir.resolve("com/xyz/rep");
        Files.createDirectories(copiedPackageDir);
        Files.copy(moduleDir.resolve("com/xyz/rep/package-info.class"),
                copiedPackageDir.resolve("package-info.class"));

        moduleInfoCopyDir = tempDir.resolve("module-copy");
        Files.createDirectories(moduleInfoCopyDir);
        Files.copy(moduleDir.resolve("module-info.class"), moduleInfoCopyDir.resolve("module-info.class"));
    }

    /** Close the scan result. */
    @AfterAll
    static void closeScanResult() {
        scanResult.close();
    }

    /**
     * The annotations of a test class.
     *
     * @param cls
     *            the class.
     * @return the annotations on the class.
     */
    private static AnnotationInfoList annotationsOn(final Class<?> cls) {
        final var classInfo = scanResult.getClassInfo(cls.getName());
        assertThat(classInfo).as(cls.getName()).isNotNull();
        return classInfo.getAllAnnotationInfo().directOnly();
    }

    /** Every repeat of a repeatable annotation is reported, in the order they were applied. */
    @Test
    public void everyRepeatOfARepeatableAnnotationIsReported() {
        final var annotations = annotationsOn(TaggedTwice.class);
        final var repeats = annotations.getRepeatable(Tag.class);
        assertThat(repeats).extracting(ai -> ai.getParameterValues().getValue("value")).containsExactly("second",
                "first");
        // The same order is seen through every view of the list
        assertThat(scanResult.getClassInfo(TaggedTwice.class.getName()).getAllAnnotationInfoRepeatable(Tag.class))
                .extracting(ai -> ai.getParameterValues().getValue("value")).containsExactly("second", "first");
        // The first repeat written is the one returned for the name
        assertThat(annotations.get(Tag.class.getName())).isSameAs(repeats.get(0));
        assertThat(annotations.asMap().get(Tag.class.getName())).isSameAs(repeats.get(0));
    }

    /**
     * The container is reported as an annotation of its own, and every query, whether it answers from the
     * annotation lists or from the class graph, agrees on that.
     */
    @Test
    public void theContainerAnnotationIsReported() {
        assertThat(annotationsOn(TaggedTwice.class).getNames()).containsExactly(NotRepeatable.class.getName(),
                Tag.class.getName(), Tag.class.getName(), Tags.class.getName());
        final var taggedTwice = scanResult.getClassInfo(TaggedTwice.class.getName());
        final var explicitContainer = scanResult.getClassInfo(ExplicitContainer.class.getName());
        for (final ClassInfo classInfo : new ClassInfo[] { taggedTwice, explicitContainer }) {
            assertThat(classInfo.getDirectAnnotationInfo(Tags.class)).as(classInfo.getName()).isNotNull();
            assertThat(classInfo.getAllAnnotationInfo().containsName(Tags.class.getName())).as(classInfo.getName())
                    .isTrue();
            assertThat(classInfo.hasAnnotation(Tags.class)).as(classInfo.getName()).isTrue();
            assertThat(classInfo.hasAnnotation(Tag.class)).as(classInfo.getName()).isTrue();
        }
        assertThat(scanResult.getClassesWithAnnotation(Tags.class).getNames())
                .containsExactlyInAnyOrder(TaggedTwice.class.getName(), ExplicitContainer.class.getName());
        assertThat(scanResult.getClassesWithAnnotation(Tag.class).getNames()).containsExactlyInAnyOrder(
                TaggedTwice.class.getName(), ExplicitContainer.class.getName(), TaggedOnce.class.getName());

        // The repeats inside an explicitly written container are reported too, in the order they were written
        assertThat(explicitContainer.getDirectAnnotationInfoRepeatable(Tag.class))
                .extracting(ai -> ai.getParameterValues().getValue("value")).containsExactly("y", "x");

        // The same holds for a method
        final var method = taggedTwice.getMethodInfo().getSingleMethod("method");
        assertThat(method.hasAnnotation(Tags.class)).isTrue();
        assertThat(method.getDirectAnnotationInfo(Tags.class)).isNotNull();
        assertThat(scanResult.getClassesWithMethodAnnotation(Tags.class).getNames())
                .containsExactly(TaggedTwice.class.getName());
    }

    /**
     * A repeatable annotation applied only once is not wrapped in a container by the compiler, and is still
     * reported by {@code getRepeatable}, as a list of one.
     */
    @Test
    public void anAnnotationAppliedOnceIsStillReportedAsARepeat() {
        assertThat(annotationsOn(TaggedOnce.class).getRepeatable(Tag.class)).singleElement()
                .satisfies(ai -> assertThat(ai.getParameterValues().getValue("value")).isEqualTo("only"));
        assertThat(annotationsOn(TaggedOnce.class).getRepeatable(Tags.class)).isEmpty();
    }

    /** An annotation that is not applied at all gives the empty list, rather than null. */
    @Test
    public void anAnnotationThatIsNotAppliedGivesTheEmptyList() {
        assertThat(annotationsOn(NotTagged.class).getRepeatable(Tag.class)).isEmpty();
        // An annotation that is present, but is not the one asked for
        assertThat(annotationsOn(TaggedTwice.class).getRepeatable("com.xyz.NoSuchAnnotation")).isEmpty();
    }

    /** An annotation that is not repeatable still has one use, which is a list of one. */
    @Test
    public void anAnnotationThatIsNotRepeatableIsAListOfOne() {
        assertThat(annotationsOn(TaggedTwice.class).getRepeatable(NotRepeatable.class)).hasSize(1);
    }

    /** The repeats of an annotation on a method are reported the same way as those on a class. */
    @Test
    public void theRepeatsOfAnAnnotationOnAMethodAreReported() {
        final var method = scanResult.getClassInfo(TaggedTwice.class.getName()).getMethodInfo()
                .getSingleMethod("method");
        assertThat(method.getAllAnnotationInfo().directOnly().getRepeatable(Tag.class))
                .extracting(ai -> ai.getParameterValues().getValue("value"))
                .containsExactly("twice", "on a method");
    }

    /**
     * The repeats of an annotation on a package or a module are reported the same way as those on a class, and two
     * repeats with the same value are both kept.
     */
    @Test
    public void theRepeatsOfAnAnnotationOnAPackageOrModuleAreReported() {
        try (var moduleScanResult = new ClassGraph().enableClasspathEntries(moduleDir.toString()).enableClassInfo()
                .enableAnnotationInfo().scan()) {
            final var packageInfo = moduleScanResult.getPackageInfo("com.xyz.rep");
            final var moduleInfo = moduleScanResult.getModuleInfo("com.xyz.rep");
            assertThat(packageInfo).isNotNull();
            assertThat(moduleInfo).isNotNull();
            for (final HasAnnotations annotated : new HasAnnotations[] { packageInfo, moduleInfo }) {
                assertThat(annotated.getDirectAnnotationInfo().getNames()).as(annotated.toString())
                        .containsExactly(MODULE_TAG, MODULE_TAG, MODULE_TAG, MODULE_TAGS);
                assertThat(annotated.getDirectAnnotationInfoRepeatable(MODULE_TAG)).as(annotated.toString())
                        .extracting(ai -> ai.getParameterValues().getValue("value")).containsExactly("b", "a", "a");
                assertThat(annotated.hasAnnotation(MODULE_TAG)).as(annotated.toString()).isTrue();
                assertThat(annotated.hasAnnotation(MODULE_TAGS)).as(annotated.toString()).isTrue();
            }
        }
    }

    /**
     * The same {@code package-info.class} found in two classpath elements gives its annotations once, not twice
     * (#347), and its repeats are still all kept.
     */
    @Test
    public void aPackageInfoFoundTwiceGivesItsAnnotationsOnce() {
        try (var twiceScanResult = new ClassGraph()
                .enableClasspathEntries(moduleDir.toString(), packageInfoCopyDir.toString()).enableClassInfo()
                .enableAnnotationInfo().scan()) {
            final var packageInfo = twiceScanResult.getPackageInfo("com.xyz.rep");
            assertThat(packageInfo).isNotNull();
            assertThat(packageInfo.getDirectAnnotationInfo().getNames()).containsExactly(MODULE_TAG, MODULE_TAG,
                    MODULE_TAG, MODULE_TAGS);
        }
    }

    /**
     * The same module found in two classpath elements gives a {@link ModuleInfo} for each, and the repeats of an
     * annotation on the module declaration are reported on both.
     */
    @Test
    public void theRepeatsOfAnAnnotationOnAModuleFoundTwiceAreReportedOnBoth() {
        try (var twiceScanResult = new ClassGraph()
                .enableClasspathEntries(moduleDir.toString(), moduleInfoCopyDir.toString()).enableClassInfo()
                .enableAnnotationInfo().scan()) {
            final var moduleInfoList = twiceScanResult.getModuleInfo();
            assertThat(moduleInfoList).hasSize(2);
            for (final var moduleInfo : moduleInfoList) {
                assertThat(moduleInfo.getDirectAnnotationInfo().getNames())
                        .as(String.valueOf(moduleInfo.getLocationURI()))
                        .containsExactly(MODULE_TAG, MODULE_TAG, MODULE_TAG, MODULE_TAGS);
            }
        }
    }

    /** The annotations {@code getRepeatable} returns keep the record of which of them are directly present. */
    @Test
    public void anInheritedAnnotationIsNotReportedAsDirectlyPresent() {
        final var allAnnotations = scanResult.getClassInfo(InheritsTag.class.getName()).getAllAnnotationInfo();
        assertThat(allAnnotations.getRepeatable(InheritedTag.class)).hasSize(1);
        assertThat(allAnnotations.getRepeatable(InheritedTag.class).directOnly()).isEmpty();
    }

    /**
     * A subclass inherits every repeat of an inherited repeatable annotation, as in
     * {@link Class#getAnnotationsByType(Class)}, not only the first one, and it inherits the container too.
     */
    @Test
    public void everyRepeatOfAnInheritedRepeatableAnnotationIsInherited() {
        final var allAnnotations = scanResult.getClassInfo(InheritsRepeats.class.getName()).getAllAnnotationInfo();
        assertThat(allAnnotations.getRepeatable(InheritedRepeat.class))
                .extracting(ai -> ai.getParameterValues().getValue("value")).containsExactly("second", "first");
        assertThat(allAnnotations.getRepeatable(InheritedRepeats.class)).hasSize(1);
        assertThat(allAnnotations.directOnly()).isEmpty();
    }

    /** Asking for a class that is not an annotation, or for nothing at all, is a programming error. */
    @Test
    public void aClassThatIsNotAnAnnotationIsRejected() {
        final var annotations = annotationsOn(TaggedTwice.class);
        @SuppressWarnings("unchecked")
        final var notAnAnnotation = (Class<? extends Annotation>) (Class<?>) String.class;
        assertThatThrownBy(() -> annotations.getRepeatable(notAnAnnotation))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> annotations.getRepeatable((Class<? extends Annotation>) null))
                .isInstanceOf(NullPointerException.class);
        assertThatThrownBy(() -> annotations.getRepeatable((String) null)).isInstanceOf(NullPointerException.class);
    }
}
